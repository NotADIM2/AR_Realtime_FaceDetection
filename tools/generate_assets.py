THUMB_W, THUMB_H = 300, 210


def thumb_base():
    """A neutral head silhouette on a dark background."""
    c = Canvas(THUMB_W, THUMB_H)
    c.fill(c.shape([(0, 0), (THUMB_W, 0), (THUMB_W, THUMB_H), (0, THUMB_H)]), c.gradient("#20242c", "#14171c"))
    c.fill(c.shape(superellipse(150, 280, 92, 85, 2.4)), "#39404b")
    c.fill(c.shape(superellipse(150, 118, 58, 74, 2.2)), c.gradient("#596270", "#454c58", 44, 192))
    return c


def paste(base, sprite, center, width):
    """Composite a straight-alpha sprite onto a flattened thumbnail."""
    height = round(sprite.shape[0] * width / sprite.shape[1])
    small = cv2.resize(sprite, (width, height), interpolation=cv2.INTER_AREA)
    x0 = round(center[0] - width / 2)
    y0 = round(center[1] - height / 2)
    x1, y1 = min(x0 + width, base.shape[1]), min(y0 + height, base.shape[0])
    sx, sy = max(-x0, 0), max(-y0, 0)
    x0, y0 = max(x0, 0), max(y0, 0)
    part = small[sy:sy + y1 - y0, sx:sx + x1 - x0]
    alpha = part[..., 3:4].astype(np.float32) / 255.0
    roi = base[y0:y1, x0:x1, :3]
    roi[:] = (part[..., :3] * alpha + roi * (1 - alpha)).astype(np.uint8)


def thumb_mesh():
    c = thumb_base()
    head = c.shape(superellipse(150, 118, 58, 74, 2.2))
    lines = c.blank()
    step = 15
    for row, y in enumerate(range(36, 204, step)):
        shift = (row % 2) * step / 2
        for x in np.arange(76 + shift, 228, step):
            a = np.array((x, y)) * SS
            for b in ((x + step, y), (x + step / 2, y + step), (x - step / 2, y + step)):
                cv2.line(lines, tuple(np.round(a).astype(int).tolist()), tuple(np.round(np.array(b) * SS).astype(int).tolist()), 255, 2, cv2.LINE_AA)
    c.fill(cv2.bitwise_and(lines, head), "#5ae0eb", 0.95)
    return c.finish()


def thumb_outline():
    c = thumb_base()
    c.fill(c.shape(superellipse(150, 118, 58, 74, 2.2)), "#2a2f38", 0.75)
    cyan = "#46e1ff"
    oval = superellipse(150, 118, 58, 74, 2.2)
    eye_l = superellipse(126, 106, 15, 7, 2, 40)
    eye_r = superellipse(174, 106, 15, 7, 2, 40)
    lips = superellipse(150, 158, 23, 8, 2, 40)
    brow_l = spline([(107, 92), (125, 85), (142, 91)], closed=False)
    brow_r = spline([(158, 91), (175, 85), (193, 92)], closed=False)
    glow = c.blank()
    for path, closed in ((oval, True), (eye_l, True), (eye_r, True), (lips, True), (brow_l, False), (brow_r, False)):
        glow = cv2.bitwise_or(glow, c.stroke(path, 2.2, closed))
    c.fill(glow, cyan, 0.9, blur=3)
    c.fill(glow, "#c8f6ff")
    return c.finish()


def build_thumbnails(sprites):
    placements = {
        "ar_glasses": ("ar_glasses", (150, 106), 134),
        "sunglasses": ("sunglasses", (150, 106), 138),
        "moustache": ("moustache", (150, 142), 64),
        "bunny_ears": ("bunny_ears", (150, 34), 138),
        "crown": ("crown", (150, 42), 112),
    }
    thumbs = {"normal": thumb_base().finish(), "mesh": thumb_mesh(), "outline": thumb_outline()}
    for key, (name, center, width) in placements.items():
        base = thumb_base().finish()
        paste(base, sprites[name], center, width)
        thumbs[key] = base
    return thumbs


def main():
    FILTER_DIR.mkdir(parents=True, exist_ok=True)
    sprites = {
        "ar_glasses": ar_glasses(),
        "sunglasses": sunglasses(),
        "moustache": moustache(),
        "bunny_ears": bunny_ears(),
        "crown": crown(),
    }
    for name, image in sprites.items():
        cv2.imwrite(str(FILTER_DIR / f"{name}.png"), image)
    for key, image in build_thumbnails(sprites).items():
        cv2.imwrite(str(FILTER_DIR / f"thumb_{key}.png"), image)
    print(f"Wrote {len(sprites)} sprites and thumbnails to {FILTER_DIR}")


if __name__ == "__main__":
    main()
