"""Draws the filter artwork and thumbnails with OpenCV and NumPy.

All artwork is original and generated by this script, so the repository contains
no third-party images. Shapes are rendered at 3x size and downsampled for smooth
edges.

Run from the project root:  python -m tools.generate_assets
"""

import math

import cv2
import numpy as np

from app.config import FILTER_DIR

SS = 3  # Supersampling factor


def bgr(hex_color):
    value = hex_color.lstrip("#")
    return tuple(int(value[i:i + 2], 16) / 255.0 for i in (4, 2, 0))


def spline(points, closed=True, samples=20):
    """Catmull-Rom spline through the given points."""
    pts = np.asarray(points, dtype=np.float64)
    n = len(pts)
    out = []
    for i in range(n if closed else n - 1):
        if closed:
            p0, p1, p2, p3 = pts[(i - 1) % n], pts[i], pts[(i + 1) % n], pts[(i + 2) % n]
        else:
            p0, p1, p2, p3 = pts[max(i - 1, 0)], pts[i], pts[i + 1], pts[min(i + 2, n - 1)]
        for t in np.linspace(0, 1, samples, endpoint=False):
            out.append(
                0.5 * ((2 * p1) + (p2 - p0) * t + (2 * p0 - 5 * p1 + 4 * p2 - p3) * t**2
                       + (3 * p1 - p0 - 3 * p2 + p3) * t**3)
            )
    if not closed:
        out.append(pts[-1])
    return np.array(out)


def superellipse(cx, cy, a, b, n=3.4, samples=180):
    t = np.linspace(0, 2 * np.pi, samples, endpoint=False)
    x = cx + a * np.sign(np.cos(t)) * np.abs(np.cos(t)) ** (2 / n)
    y = cy + b * np.sign(np.sin(t)) * np.abs(np.sin(t)) ** (2 / n)
    return np.column_stack((x, y))


def rotated(points, angle_deg, center):
    angle = math.radians(angle_deg)
    c, s = math.cos(angle), math.sin(angle)
    p = np.asarray(points, dtype=np.float64) - center
    return np.column_stack((p[:, 0] * c - p[:, 1] * s, p[:, 0] * s + p[:, 1] * c)) + center


class Canvas:
    """A premultiplied floating-point BGRA drawing surface."""

    def __init__(self, width, height):
        self.width, self.height = width, height
        self.image = np.zeros((height * SS, width * SS, 4), np.float32)

    def blank(self):
        return np.zeros(self.image.shape[:2], np.uint8)

    def shape(self, points):
        mask = self.blank()
        cv2.fillPoly(mask, [np.round(np.asarray(points) * SS * 16).astype(np.int32)], 255, cv2.LINE_8, 4)
        return mask

    def stroke(self, points, thickness, closed=False):
        mask = self.blank()
        pts = np.round(np.asarray(points) * SS * 16).astype(np.int32)
        cv2.polylines(mask, [pts], closed, 255, max(int(thickness * SS), 1), cv2.LINE_8, 4)
        return mask

    def gradient(self, top, bottom, y0=0, y1=None):
        """Vertical colour gradient between y0 and y1."""
        y1 = self.height if y1 is None else y1
        t = np.clip((np.arange(self.height * SS) / SS - y0) / max(y1 - y0, 1), 0, 1)[:, None, None]
        top, bottom = np.array(bgr(top), np.float32), np.array(bgr(bottom), np.float32)
        return np.broadcast_to(top * (1 - t) + bottom * t, self.image.shape[:2] + (3,)).astype(np.float32)

    def fill(self, mask, paint, opacity=1.0, blur=0.0):
        """Composite paint through a mask. opacity may be a number or a per-pixel array."""
        a = mask.astype(np.float32) / 255.0
        if blur:
            a = cv2.GaussianBlur(a, (0, 0), blur * SS)
        a = a * opacity
        if isinstance(paint, str):
            paint = np.array(bgr(paint), np.float32)
        self.image[..., :3] = paint * a[..., None] + self.image[..., :3] * (1 - a[..., None])
        self.image[..., 3] = a + self.image[..., 3] * (1 - a)

    def erase(self, mask):
        a = mask.astype(np.float32)[..., None] / 255.0
        self.image *= 1 - a

    def vertical_opacity(self, top, bottom, y0, y1):
        t = np.clip((np.arange(self.height * SS) / SS - y0) / max(y1 - y0, 1), 0, 1)[:, None]
        return np.broadcast_to(top * (1 - t) + bottom * t, self.image.shape[:2]).astype(np.float32)

    def finish(self):
        """Downsample and return a straight-alpha BGRA uint8 image."""
        small = cv2.resize(self.image, (self.width, self.height), interpolation=cv2.INTER_AREA)
        alpha = np.clip(small[..., 3:4], 0, 1)
        color = np.where(alpha > 1e-4, small[..., :3] / np.maximum(alpha, 1e-4), 0)
        return (np.clip(np.dstack((color, alpha)), 0, 1) * 255 + 0.5).astype(np.uint8)


def ar_glasses():
    """Tech glasses: gunmetal frame, cyan lenses and a heads-up display."""
    c = Canvas(900, 320)
    lens_a = superellipse(235, 160, 190, 122)
    lens_b = superellipse(665, 160, 190, 122)
    inner_a = superellipse(235, 160, 170, 102)
    inner_b = superellipse(665, 160, 170, 102)
    cyan = "#3fe0ff"

    # Outer glow, removed from the lens area afterwards.
    glow = cv2.bitwise_or(c.shape(lens_a), c.shape(lens_b))
    c.fill(glow, cyan, 0.5, blur=9)
    c.erase(cv2.bitwise_or(c.shape(inner_a), c.shape(inner_b)))

    # Lens tint, stronger at the top.
    lens_mask = cv2.bitwise_or(c.shape(inner_a), c.shape(inner_b))
    c.fill(lens_mask, c.gradient("#28b8e8", "#0b5f8a", 60, 260), c.vertical_opacity(0.34, 0.16, 60, 260))

    # Heads-up display elements in the image-right lens.
    reticle = np.array([(665 + 54 * math.cos(t), 160 + 54 * math.sin(t)) for t in np.linspace(0.3, 2.6, 40)])
    c.fill(c.stroke(reticle, 3), cyan, 0.95)
    c.fill(c.stroke(rotated(reticle, 180, (665, 160)), 3), cyan, 0.95)
    c.fill(c.stroke([(665, 128), (665, 192)], 2), cyan, 0.8)
    c.fill(c.stroke([(633, 160), (697, 160)], 2), cyan, 0.8)
    # Data bars in the image-left lens.
    for i, length in enumerate((120, 84, 150, 62)):
        y = 118 + i * 28
        c.fill(c.stroke([(140, y), (140 + length, y)], 5), cyan, 0.85)

    # Frame.
    frame = cv2.bitwise_or(c.shape(lens_a), c.shape(lens_b))
    frame = cv2.subtract(frame, lens_mask)
    c.fill(frame, c.gradient("#59626f", "#1a1e25", 30, 290))
    edge = cv2.bitwise_or(c.stroke(inner_a, 3, True), c.stroke(inner_b, 3, True))
    c.fill(edge, cyan)

    # Bridge and temple hinges.
    bridge = c.stroke(spline([(418, 136), (450, 118), (482, 136)], closed=False), 18)
    c.fill(bridge, c.gradient("#59626f", "#2a2f38", 100, 160))
    for x0, x1 in ((6, 52), (848, 894)):
        c.fill(c.shape(superellipse((x0 + x1) / 2, 118, (x1 - x0) / 2, 16, 4)), "#2a2f38")
    return c.finish()


def sunglasses():
    """Aviator sunglasses: gold wire frame and dark gradient lenses."""
    c = Canvas(900, 330)
    half = np.array([(0.05, -0.30), (0.35, -0.46), (0.75, -0.48), (0.98, -0.30), (0.95, 0.05),
                     (0.72, 0.40), (0.40, 0.47), (0.14, 0.30), (0.02, 0.0)])
    size = np.array((390.0, 300.0))
    right = spline(half * size + (490, 165))
    left = spline((half * (-1, 1)) * size + (410, 165))
    lenses = cv2.bitwise_or(c.shape(left), c.shape(right))

    c.fill(lenses, c.gradient("#14161a", "#3a2a22", 20, 310), c.vertical_opacity(0.96, 0.82, 20, 310))

    # Diagonal reflections, clipped to the lens shape.
    for offset, width, strength in ((0, 46, 0.16), (70, 16, 0.12)):
        for x_base in (120, 600):
            band = c.shape([(x_base + offset, 300), (x_base + offset + width, 300),
                            (x_base + offset + width + 150, 30), (x_base + offset + 150, 30)])
            c.fill(cv2.bitwise_and(band, lenses), "#ffffff", strength)

    gold = c.gradient("#ffe8a3", "#a8741e", 10, 320)
    rims = cv2.bitwise_or(c.stroke(left, 9, True), c.stroke(right, 9, True))
    c.fill(rims, gold)
    c.fill(c.stroke(spline([(398, 88), (450, 76), (502, 88)], closed=False), 8), gold)
    c.fill(c.stroke(spline([(415, 165), (450, 150), (485, 165)], closed=False), 7), gold)
    return c.finish()


def moustache():
    """Handlebar moustache with fine hair strokes."""
    c = Canvas(720, 240)
    half = np.array([(0.0, 0.03), (0.10, -0.24), (0.40, -0.26), (0.68, -0.08), (0.84, -0.12), (0.93, -0.32),
                     (1.0, -0.42), (1.0, -0.18), (0.86, 0.14), (0.58, 0.32), (0.26, 0.34), (0.08, 0.22)])
    half_size = np.array((350.0, 215.0))
    center = np.array((360.0, 118.0))
    left = spline(half * (-1, 1) * half_size + center)
    right = spline(half * half_size + center)
    mask = cv2.bitwise_or(c.shape(left), c.shape(right))
    c.fill(mask, c.gradient("#3b2416", "#180d07", 40, 200))

    # Hair strokes fan out from the centre.
    rng = np.random.default_rng(7)
    hair = c.blank()
    for _ in range(420):
        x = rng.uniform(25, 695)
        y = rng.uniform(20, 215)
        side = 1 if x > 360 else -1
        angle = side * (0.28 + rng.uniform(-0.15, 0.2))
        length = rng.uniform(16, 40)
        start = np.array((x, y))
        end = start + (side * length * math.cos(angle), abs(length * math.sin(angle)) * 0.9)
        cv2.line(hair, tuple(np.round(start * SS).astype(int).tolist()), tuple(np.round(end * SS).astype(int).tolist()), 255, 2, cv2.LINE_AA)
    c.fill(cv2.bitwise_and(hair, mask), "#7a5233", 0.55)

    # Soft highlight along the upper edge.
    highlight = cv2.bitwise_and(c.shape(spline(np.array([(0.04, -0.17), (0.40, -0.20), (0.70, -0.02), (0.55, 0.05), (0.20, -0.04)]) * half_size + center)), mask)
    c.fill(highlight, "#b08560", 0.28, blur=5)
    mirrored = np.array([(0.04, -0.17), (0.40, -0.20), (0.70, -0.02), (0.55, 0.05), (0.20, -0.04)]) * (-1, 1) * half_size + center
    c.fill(cv2.bitwise_and(c.shape(spline(mirrored)), mask), "#b08560", 0.28, blur=5)
    return c.finish()


def bunny_ears():
    """Two soft bunny ears on a headband."""
    c = Canvas(820, 660)
    outer = np.array([(-22, 0), (-74, -150), (-90, -320), (-60, -490), (0, -560), (60, -490), (90, -320), (74, -150), (22, 0)], float)
    inner = np.array([(-8, -50), (-42, -170), (-52, -320), (-34, -445), (0, -500), (34, -445), (52, -320), (42, -170), (8, -50)], float)

    for x, angle in ((240, -13), (580, 13)):
        base = np.array((x, 600.0))
        ear = rotated(spline(outer + base), angle, base)
        centre = rotated(spline(inner + base), angle, base)
        ear_mask = c.shape(ear)
        c.fill(ear_mask, "#4a4550", 0.3, blur=6)
        c.fill(ear_mask, c.gradient("#ffffff", "#d9d5de", 40, 610))
        c.fill(c.shape(centre), c.gradient("#ffc0d0", "#ee7c9f", 60, 590))
        # Shading deepens the inner ear towards its base.
        c.fill(c.shape(centre), "#b33f6a", c.vertical_opacity(0.0, 0.35, 330, 590))

    # Headband curves over the top of the head.
    band = spline([(120, 642), (250, 596), (410, 578), (570, 596), (700, 642)], closed=False)
    c.fill(c.stroke(band, 26), c.gradient("#ff8fb0", "#d6497c", 570, 650))
    c.fill(c.stroke(band - (0, 6), 6), "#ffd0de", 0.75)
    return c.finish()


def crown():
    """Gold crown with jewels."""
    c = Canvas(820, 460)
    tips = [(70, 130), (235, 78), (410, 36), (585, 78), (750, 130)]
    outline = [
        (92, 408), (70, 130), (165, 262), (235, 78), (320, 248), (410, 36), (500, 248),
        (585, 78), (655, 262), (750, 130), (728, 408),
    ]

    gold = c.gradient("#fff0a0", "#c98510", 40, 410).copy()
    # Horizontal brightness variation suggests curved metal.
    x = np.arange(c.width * SS) / (c.width * SS)
    gold *= (1.0 + 0.16 * np.cos((x - 0.5) * 16))[None, :, None]
    gold = np.clip(gold, 0, 1)

    body = c.shape(outline)
    c.fill(c.stroke(outline, 10, True), "#6f4706")
    c.fill(body, gold)

    band = c.shape([(92, 340), (728, 340), (728, 408), (92, 408)])
    c.fill(band, c.gradient("#e9a621", "#8d5b0a", 340, 408))
    c.fill(c.stroke([(92, 340), (728, 340)], 5), "#fff0a0", 0.9)
    c.fill(c.stroke([(92, 408), (728, 408)], 5), "#6f4706")

    for (tx, ty) in tips:
        ball = superellipse(tx, ty - 6, 21, 21, 2, 60)
        c.fill(c.stroke(ball, 5, True), "#6f4706")
        c.fill(c.shape(ball), c.gradient("#fff7cf", "#d9971a", ty - 28, ty + 16))
        c.fill(c.shape(superellipse(tx - 7, ty - 13, 6, 6, 2, 30)), "#ffffff", 0.9)

    for jx, size, top, bottom in ((200, 18, "#7fb2ff", "#123f9c"), (410, 25, "#ff8a8a", "#a3101f"), (620, 18, "#8af0ae", "#0d7a3a")):
        jewel = superellipse(jx, 374, size * 1.3, size, 2, 60)
        c.fill(c.stroke(jewel, 5, True), "#6f4706")
        c.fill(c.shape(jewel), c.gradient(top, bottom, 374 - size, 374 + size))
        c.fill(c.shape(superellipse(jx - size * 0.4, 374 - size * 0.4, size * 0.26, size * 0.2, 2, 30)), "#ffffff", 0.85)
    return c.finish()


